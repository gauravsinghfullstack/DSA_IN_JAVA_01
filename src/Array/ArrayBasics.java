package Array;


public class ArrayBasics {
    static void main(String[] args) {
        int[] x = {6,19,7,69,9,171,5};

                 //indexing number
        System.out.println(x[5]);


                // Updating Element ---- mutability(change)
        x[3] = 89;
        System.out.println(x[3]);


    }
}
